-- =============================================================================
-- 第 2 章の後: 計算する力を元の大きさに戻す 💰
-- =============================================================================
-- dbt の「実行」と「テスト」が終わったら、ファイル全体を実行します。
--
-- LARGE のままでもデータは壊れませんが、その後の処理も大きな計算機で動きます。
-- ハンズオンの残りは XSMALL で十分なので、使い終わったら小さく戻します。
-- =============================================================================

USE ROLE ACCOUNTADMIN;

ALTER WAREHOUSE BCAST_HANDSON_WH
  SET WAREHOUSE_SIZE = 'XSMALL';

-- size が X-Small と表示されたら後片付け完了です。
SHOW WAREHOUSES LIKE 'BCAST_HANDSON_WH';
