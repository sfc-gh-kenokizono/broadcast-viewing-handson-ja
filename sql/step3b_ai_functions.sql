-- =============================================================================
-- 第 3b 章  AI 関数でテキストを数字の隣に並べる（補足）
-- =============================================================================
-- 実行するロール: ACCOUNTADMIN
-- 所要時間の目安: 12 分
--
-- この章の位置づけ
--   ここまでで扱ってきたのは、行と列に収まっている数字と符号でした。
--   一方、実務のデータには文章の列が混ざります。このハンズオンのデータでは
--   コマーシャル素材の説明文（CM_MASTER.CREATIVE_DESC）がそれです。
--
--   文章は、そのままでは集計できません。「訴求軸ごとのリーチ」を出したくても、
--   訴求軸という列が存在しないためです。従来はここで人が目視で分類して
--   スプレッドシートに転記していました。
--
--   この章では、その分類を SQL の中でやります。外に持ち出さず、
--   モデルを用意せず、関数を 1 つ書くだけです。
--
-- この章でやること
--   1. 文章を分類する（AI_CLASSIFY）
--   2. 文章から項目を取り出す（AI_EXTRACT）
--   3. 複数の文章をまとめて要約する（AI_AGG）
--   4. 取り出した訴求軸を、第 2 章で作ったリーチの数字と突き合わせる
--
-- 前提
--   第 2 章まで実行し終わっていること（4 で MART スキーマを参照します）。
--   第 0 章で CORTEX_ENABLED_CROSS_REGION を ANY_REGION にしてあること。
--
-- 費用について
--   AI 関数の費用は、処理した文字数（トークン数）で決まります。
--   この章で処理するのは 20 行、1 行あたり 100 文字程度です。
--   同じ関数を 100 万行に流すときは、まず LIMIT を付けて試すのが基本です。
-- =============================================================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE BCAST_HANDSON_WH;
USE SCHEMA BCAST_VIEWING_HANDSON.RAW;


-- =============================================================================
-- 0. 素材になる文章を見る
-- =============================================================================
-- まず、これから相手にするデータを見ておきます。
-- 20 件のコマーシャル素材に、それぞれ説明文が付いています。

SELECT
  CM_ID          AS "素材ID",
  ADVERTISER     AS "広告主",
  CATEGORY       AS "商品カテゴリ",
  CREATIVE_DESC  AS "素材の説明文"
FROM CM_MASTER
WHERE IS_ANALYSIS_TARGET
ORDER BY CM_ID
LIMIT 5;

-- 商品カテゴリは列として持っています。
-- 一方「誰に向けた表現なのか」は、説明文の中にしか書かれていません。


-- =============================================================================
-- 1. 文章を分類する（AI_CLASSIFY）
-- =============================================================================
-- やること
--   説明文を読んで、あらかじめ決めた訴求軸のどれに当たるかを判定させます。
--   分類の基準を学習させる作業はありません。選択肢を配列で渡すだけです。

-- 1-1 まず 1 件で試します
SELECT AI_CLASSIFY(
  '夏の屋外で炭酸飲料を飲み、爽快な表情を見せる 15 秒の映像です。若い世代に向けた明るいトーンで、商品名を最後に大きく表示します。',
  ['若年層向け', '家族向け', '健康志向', '高級感', '安心・安全']
) AS "判定結果";

-- 返ってくるのは {"labels": ["若年層向け"]} という形です。
-- labels が配列になっているのは、複数当てはまる場合に備えているためです。


-- 1-2 20 件すべてを、複数ラベルで分類します
-- output_mode を multi にすると、当てはまるものを全部返します。
-- task_description は、何を判定させたいのかの説明です。省略できますが、
-- 書いたほうが精度が上がります。
SELECT
  CM_ID                                     AS "素材ID",
  ADVERTISER                                AS "広告主",
  CREATIVE_DESC                             AS "素材の説明文",
  ARRAY_TO_STRING(
    AI_CLASSIFY(
      CREATIVE_DESC,
      ['若年層向け', '家族向け', '健康志向', '高級感', '安心・安全', '価格訴求'],
      {
        'output_mode': 'multi',
        'task_description': 'テレビコマーシャルの素材説明文から、その素材がどの訴求軸を使っているかを判定してください'
      }
    ):labels::ARRAY,
    ' / '
  )                                         AS "訴求軸"
FROM CM_MASTER
WHERE IS_ANALYSIS_TARGET
ORDER BY CM_ID;

-- 結果の見かた
--   説明文と訴求軸を左右に並べています。1 行ずつ、納得できる判定になっているか
--   確かめてください。人が読んで違うと思う行があれば、それが AI 関数の限界です。
--   選択肢の言葉を変える、task_description を具体的にする、といった調整で
--   だいたい寄せられます。


-- =============================================================================
-- 2. 文章から項目を取り出す（AI_EXTRACT）
-- =============================================================================
-- 分類は「決めた選択肢のどれか」を選ばせるものでした。
-- こちらは「文章の中に書かれている内容そのもの」を項目ごとに取り出します。
--
-- 質問を key と value の形で渡すと、その形で答えが返ります。
-- どういう答えが返るかを、こちら側で決められるのが要点です。

SELECT
  CM_ID                                             AS "素材ID",
  ADVERTISER                                        AS "広告主",
  x:response:"登場人物"::STRING                     AS "登場人物",
  x:response:"舞台"::STRING                         AS "舞台",
  x:response:"訴求ポイント"::STRING                 AS "訴求ポイント"
FROM (
  SELECT
    CM_ID,
    ADVERTISER,
    AI_EXTRACT(
      text => CREATIVE_DESC,
      responseFormat => {
        '登場人物':   '誰が登場しますか',
        '舞台':       'どこが舞台ですか',
        '訴求ポイント': '何を訴求していますか'
      }
    ) AS x
  FROM CM_MASTER
  WHERE IS_ANALYSIS_TARGET
)
ORDER BY CM_ID;

-- 押さえておきたいこと
--   returnされるのは {"error": ..., "response": {...}} という形です。
--   欲しい項目は x:response:"項目名" で取り出します。日本語の key は
--   二重引用符で囲みます。
--   1 回の呼び出しで 3 項目まとめて取れるので、項目ごとに 3 回呼ぶより
--   費用も時間も少なくて済みます。


-- =============================================================================
-- 3. 複数の文章をまとめて要約する（AI_AGG）
-- =============================================================================
-- ここまでは 1 行に対して 1 つの答えを返す使い方でした。
-- AI_AGG は SUM や AVG と同じ集約関数です。GROUP BY でまとめた複数行の文章を
-- 読んで、グループごとに 1 つの答えを返します。
--
-- SQL で書けなかったのはここです。文章を 20 件読んで傾向をまとめる、という
-- 処理に相当する集約関数は、これまで存在しませんでした。

SELECT
  CATEGORY   AS "商品カテゴリ",
  COUNT(*)   AS "素材数",
  AI_AGG(
    CREATIVE_DESC,
    'これらはテレビコマーシャルの素材説明文です。この商品カテゴリの素材に共通する表現の傾向を、日本語で 2 文以内にまとめてください。'
  )          AS "表現の傾向"
FROM CM_MASTER
WHERE IS_ANALYSIS_TARGET
GROUP BY CATEGORY
ORDER BY "素材数" DESC;

-- 押さえておきたいこと
--   第 2 引数が指示文です。「2 文以内」「日本語で」のように出力の形を
--   指定できます。ここを変えるだけで、同じデータから別の観点の要約が出せます。
--
--   要約だけが目的なら AI_SUMMARIZE_AGG という関数もあります。こちらは
--   指示文を取らない代わりに、書くことが少なくて済みます。
--
--   なお、感情を数値化する AI_SENTIMENT という関数もありますが、
--   このデータには使っていません。素材の説明文は制作側が書いた説明であって、
--   誰かの意見や感想ではないため、点数を付けても読み方がないからです。
--   視聴者アンケートや問い合わせ履歴があれば、そこが出番になります。


-- =============================================================================
-- 4. AI が作った列を、リーチの数字と突き合わせる
-- =============================================================================
-- ここがこの章の目的です。
-- 訴求軸という列が手に入ったので、第 2 章で作ったリーチとフリークエンシーを
-- 訴求軸ごとに見られるようになります。
--
-- なぜ一度テーブルに落とすのか
--   AI 関数は呼ぶたびに費用と時間がかかります。結合のたびに呼び直すのは
--   無駄なので、判定結果は一度テーブルにして、以降はそれを参照します。
--   これは AI 関数に限らず、重い計算を含む列の扱い方の基本です。

-- 4-1 判定結果をテーブルにします
CREATE OR REPLACE TABLE BCAST_VIEWING_HANDSON.MART.CM_CREATIVE_TAGS AS
SELECT
  CM_ID,
  ADVERTISER,
  CATEGORY,
  CREATIVE_DESC,
  AI_CLASSIFY(
    CREATIVE_DESC,
    ['若年層向け', '家族向け', '健康志向', '高級感', '安心・安全', '価格訴求'],
    {
      'output_mode': 'multi',
      'task_description': 'テレビコマーシャルの素材説明文から、その素材がどの訴求軸を使っているかを判定してください'
    }
  ):labels::ARRAY AS APPEAL_AXES
FROM CM_MASTER
WHERE IS_ANALYSIS_TARGET;

SELECT COUNT(*) AS "判定した素材数" FROM BCAST_VIEWING_HANDSON.MART.CM_CREATIVE_TAGS;


-- 4-2 訴求軸ごとのリーチとフリークエンシーを出します
-- 1 つの素材に訴求軸が複数付いているので、FLATTEN で 1 行 1 訴求軸に開きます。
-- 同じ素材が複数の訴求軸に数えられます。合計しても全体には一致しません。
SELECT
  ax.VALUE::STRING                 AS "訴求軸",
  COUNT(DISTINCT t.CM_ID)          AS "素材数",
  COUNT(DISTINCT f.COMMON_ID)      AS "リーチ（受信機数）",
  ROUND(
    SUM(f.CONTACT_COUNT) / NULLIF(COUNT(DISTINCT f.COMMON_ID), 0),
    2
  )                                AS "平均フリークエンシー",
  SUM(f.CONTACT_COUNT)             AS "インプレッション"
FROM BCAST_VIEWING_HANDSON.MART.CM_CREATIVE_TAGS t
INNER JOIN BCAST_VIEWING_HANDSON.MART.MART_FREQUENCY f
  ON t.CM_ID = f.CM_ID
, LATERAL FLATTEN(INPUT => t.APPEAL_AXES) ax
GROUP BY 1
ORDER BY "リーチ（受信機数）" DESC;

-- 結果の読み方
--   訴求軸ごとに、どれだけの受信機に何回届いたかが並びます。
--   ここまで来ると「家族向けの表現はリーチが広いが回数が少ない」といった
--   比較ができます。もともとデータに無かった軸での比較です。
--
--   ただし、これは表現と接触の関係であって、効果ではありません。
--   その訴求軸が売上につながったかは、このデータには入っていません。


-- =============================================================================
-- この章のまとめ
-- =============================================================================
--   AI_CLASSIFY   決めた選択肢に分類する。output_mode を multi にすると複数返る
--   AI_EXTRACT    文章から項目を取り出す。返る形をこちらで決められる
--   AI_AGG        GROUP BY した複数行の文章を読んで、グループごとに 1 つ返す
--
--   共通していること
--     どれも SQL の関数です。データを外に出さず、モデルの用意も学習もなく、
--     権限は既存のロールのまま使えます。
--     結果は普通の列なので、そのまま GROUP BY や JOIN の材料になります。
--
--   CM_CREATIVE_TAGS は、文章から作った分類を数値分析へ組み合わせる例です。
--   第 4 章のエージェントとは独立しているため、この任意章を飛ばしても進めます。
-- =============================================================================
