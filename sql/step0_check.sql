-- =============================================================================
-- 1. どのアカウント、どのロールで作業しているか
-- =============================================================================
-- これから 2 時間、同じ 1 つの環境で作業します。ここで確定させておくと、
-- 途中で「作ったはずのものが見つからない」という迷子になりません。
--
-- 日本語の列名はダブルクォートで囲みます。囲まないと Snowflake は識別子として
-- 解釈できず、syntax error になります。

SELECT
  CURRENT_ACCOUNT()  AS "アカウント",
  CURRENT_REGION()   AS "リージョン",
  CURRENT_USER()     AS "ユーザー",
  CURRENT_ROLE()     AS "ロール",
  CURRENT_VERSION()  AS "バージョン";

-- 確認すること
--   ロールが ACCOUNTADMIN になっていること。
--   なっていない場合は、ワークシート右上のロール切り替えから変更してください。
--   複数のアカウントをお持ちの場合は、ここで 1 つに決めてしまってください。

-- 明示的に切り替えておくこともできます
USE ROLE ACCOUNTADMIN;

-- =============================================================================
-- 2. 使うウェアハウスを選ぶ
-- =============================================================================
-- SELECT で計算をするには、ウェアハウス（計算資源）が選ばれている必要があります。
-- 選ばれていないと、次のエラーになります。
--   No active warehouse selected in the current session.
--
-- このハンズオン用のウェアハウスは第 1 章で作ります。第 0 章の時点では
-- トライアルに最初から用意されているものを使います。

SHOW WAREHOUSES;

-- 上の一覧に COMPUTE_WH があればそれを使います。
-- 名前が違う場合は、一覧に出てきた名前に読み替えてください。
USE WAREHOUSE COMPUTE_WH;

-- =============================================================================
-- 3. Cortex が使えることを確認する
-- =============================================================================
-- 第 3 章以降で使う AI 機能が、このアカウントで利用できるかを確認します。
--
-- 関数名について
--   AI_COMPLETE を使います。以前は SNOWFLAKE.CORTEX.COMPLETE と書きましたが、
--   そちらは後方互換のために残されている旧名で、2026 年内に廃止予定です。
--   新しく書くものは AI_COMPLETE を使ってください。名前空間の接頭辞は要りません。

-- モデルは提供されているリージョンが限られます。自分のアカウントのリージョンに
-- ないモデルを呼ぶと Cortex は「使えません」と返すだけで、勝手に他のリージョンへは
-- 出ていきません。この設定を入れると、足りないモデルを他のリージョンで処理します。
--
-- 本番では、データが処理されるリージョンが変わることになるため、
-- 置き場所に関する規程を確認したうえで判断してください。
-- ここはトライアルでの検証環境なので、詰まらないように最初から有効にします。
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

SELECT AI_COMPLETE(
  'claude-sonnet-4-5',
  '一言で自己紹介してください'
) AS "応答";

-- 文章が返ってくれば、第 3 章以降で使う機能が利用できます。
--
-- 設定が入っているか確認したい場合はこちらです。
SHOW PARAMETERS LIKE 'CORTEX_ENABLED_CROSS_REGION' IN ACCOUNT;

-- =============================================================================
-- 4. ワークスペースが使えることを確認する
-- =============================================================================
-- 第 2 章では Snowsight のワークスペースで dbt を動かします。
-- ワークスペースは個人データベースの中に作られるため、この機能が
-- アカウントで有効になっている必要があります。

SHOW PARAMETERS LIKE 'ENABLE_PERSONAL_DATABASE' IN ACCOUNT;

-- value が true であれば有効です。
-- 行が返らない、または false の場合は次を実行してください。
--
-- ALTER ACCOUNT SET ENABLE_PERSONAL_DATABASE = TRUE;
--
-- 画面から確認する場合は、Snowsight の左メニューで Projects の下に
-- Workspaces が表示されていれば有効です。

-- =============================================================================
-- 5. 使う容量の目安
-- =============================================================================
-- このハンズオンで扱うデータは圧縮後で 20 メガバイト程度、Snowflake 上に
-- 展開しても数百メガバイトです。ウェアハウスは XSMALL を使い、いちばん重い
-- 処理でも 1 分程度で終わります。トライアルの残り容量を大きく消費しません。
--
-- 各章の終わりに、その章で使った時間とクレジットを確認するクエリがあります。
-- 実際の規模で見積もりを立てるときの手がかりになります。

