-- =============================================================================
-- 第 0 章 環境の確認
-- =============================================================================
-- このファイルでやること
--   1. どのアカウント、どのロールで作業しているかを確認する
--   2. 使うウェアハウスを選ぶ
--   3. Cortex（AI 機能）が使えることを確認する
--   4. ワークスペースが使えることを確認する
--
-- 事前に決めておくこと
--   ありません。上から順に実行してください。
--
-- 進め方
--   Snowsight で新しい SQL ワークシートを開き、このファイルの内容を貼り付けてから、
--   上から順に実行していきます。
-- =============================================================================

-- =============================================================================
-- 1. どのアカウント、どのロールで作業しているか
-- =============================================================================
-- これから 2 時間、同じ 1 つの環境で作業します。ここで確定させておくと、
-- 途中で「作ったはずのものが見つからない」という迷子になりません。
--
-- 日本語の列名はダブルクォートで囲みます。囲まないと Snowflake は識別子として
-- 解釈できず、syntax error になります。

SELECT
  CURRENT_ACCOUNT()  AS "アカウント",
  CURRENT_REGION()   AS "リージョン",
  CURRENT_USER()     AS "ユーザー",
  CURRENT_ROLE()     AS "ロール",
  CURRENT_VERSION()  AS "バージョン";

-- 確認すること
--   ロールが ACCOUNTADMIN になっていること。
--   なっていない場合は、ワークシート右上のロール切り替えから変更してください。
--   複数のアカウントをお持ちの場合は、ここで 1 つに決めてしまってください。

-- 明示的に切り替えておくこともできます
USE ROLE ACCOUNTADMIN;

-- =============================================================================
-- 2. 使うウェアハウスを選ぶ
-- =============================================================================
-- SELECT で計算をするには、ウェアハウス（計算資源）が選ばれている必要があります。
-- 選ばれていないと、次のエラーになります。
--   No active warehouse selected in the current session.
--
-- このハンズオン用のウェアハウスは第 1 章で作ります。第 0 章の時点では
-- トライアルに最初から用意されているものを使います。

SHOW WAREHOUSES;

-- 上の一覧に COMPUTE_WH があればそれを使います。
-- 名前が違う場合は、一覧に出てきた名前に読み替えてください。
USE WAREHOUSE COMPUTE_WH;

-- =============================================================================
-- 3. Cortex が使えることを確認する
-- =============================================================================
-- 第 3 章以降で使う AI 機能が、このアカウントで利用できるかを確認します。

-- モデルは提供されているリージョンが限られます。自分のアカウントのリージョンに
-- ないモデルを呼ぶと Cortex は「使えません」と返すだけで、勝手に他のリージョンへは
-- 出ていきません。この設定を入れると、足りないモデルを他のリージョンで処理します。
--
-- 本番では、データが処理されるリージョンが変わることになるため、
-- 置き場所に関する規程を確認したうえで判断してください。
-- ここはトライアルでの検証環境なので、詰まらないように最初から有効にします。
ALTER ACCOUNT SET CORTEX_ENABLED_CROSS_REGION = 'ANY_REGION';

SELECT AI_COMPLETE(
  'claude-sonnet-4-5',
  '一言で自己紹介してください'
) AS "応答";

-- 文章が返ってくれば、第 3 章以降で使う機能が利用できます。
--
-- 設定が入っているか確認したい場合はこちらです。
SHOW PARAMETERS LIKE 'CORTEX_ENABLED_CROSS_REGION' IN ACCOUNT;

-- =============================================================================
-- 4. 教材を取り込むための扉を開ける
-- =============================================================================
-- ここから先の章では、教材のファイル（SQL、dbt のモデル、アプリのコード）を
-- Snowsight のワークスペースに取り込んで、そこから直接実行していきます。
-- コピーと貼り付けはこの第 0 章だけで終わりです。
--
-- そのために必要なのが API 統合です。これは
-- 「このアカウントから外に出ていってよい先」を宣言するオブジェクトです。
-- ここに書いていないドメインには接続できません。外部との通信を
-- 管理者が宣言した先に限定できる、というのがこの仕組みの意図です。
--
-- API 統合はアカウントに属するオブジェクトなので、データベースは要りません。
-- IF NOT EXISTS を付けているので、あとで第 1 章を実行しても作り直されません。

CREATE API INTEGRATION IF NOT EXISTS BCAST_GIT_API
  API_PROVIDER = git_https_api
  API_ALLOWED_PREFIXES = ('https://github.com/sfc-gh-kenokizono')
  ENABLED = TRUE;

SHOW INTEGRATIONS LIKE 'BCAST_GIT_API';

-- 1 行返ってくれば準備完了です。
--
-- このリポジトリは公開しているので、認証情報は必要ありません。
-- 非公開リポジトリを使う場合の手順は sql/step1_setup.sql の末尾にあります。

-- =============================================================================
-- 5. ワークスペースを作る（画面操作）
-- =============================================================================
-- 次は SQL ではなく画面での操作です。
--
--   1. 左メニューで Projects の下の Workspaces を開く
--   2. ワークスペースのメニュー（左上。初回は + Add New）から
--      From Git repository を選ぶ
--   3. 次のように入力する
--
--        Repository URL   https://github.com/sfc-gh-kenokizono/broadcast-viewing-handson-ja.git
--        ワークスペース名   bcast_viewing
--        API Integration   BCAST_GIT_API
--        認証方法          Public repository
--
--   4. Create を選ぶ
--
-- 左側にリポジトリの中身が表示されます。以降の章では、ここから
-- ファイルを開いて実行していきます。
--
-- 注意
--   初期画面に並んでいる「dbt プロジェクト」ボタンは押さないでください。
--   あれは空のプロジェクトを新規作成するもので、教材は入ってきません。
--
-- ワークスペースは初めて開いたときに自動で用意されます。
-- 事前の有効化は必要ありません。

-- =============================================================================
-- 6. 使う容量の目安
-- =============================================================================
-- このハンズオンで扱うデータは圧縮後で 20 メガバイト程度、Snowflake 上に
-- 展開しても数百メガバイトです。ウェアハウスは XSMALL を使い、いちばん重い
-- 処理でも 1 分程度で終わります。トライアルの残り容量を大きく消費しません。
--
-- 各章の終わりに、その章で使った時間とクレジットを確認するクエリがあります。
-- 実際の規模で見積もりを立てるときの手がかりになります。

